# CLI
# --------------------------------------------------------------------------- #


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="python -m D.release_fork",
        description="Fork the run into an interim-release anneal branch (manifest amendment + runbook).",
    )
    parser.add_argument("--checkpoint", required=True, help="checkpoint directory (contains meta.json)")
    parser.add_argument("--out", required=True, help="output directory for manifest.json + RELEASE_FORK.md")
    parser.add_argument("--manifest", required=True, help="path to the CURRENT run manifest JSON")
    parser.add_argument("--config", required=True, help="RunConfig base YAML (e.g. C/configs/base.yaml)")
    parser.add_argument("--overlay", action="append", default=[], help="config overlay YAML (repeatable)")
    parser.add_argument("--decay-tokens", type=int, required=True, help="anneal budget (e.g. 150e9 for v0.9)")
    parser.add_argument("--effective-window", type=int, required=True, help=">= 2 windows ahead of chain head")
    parser.add_argument("--committed-block", type=int, required=True, help="block the amendment commits at")
    parser.add_argument("--anneal-dataset", default="anneal", help="DatasetManifestRef.name to anneal on")
    parser.add_argument("--phase-name", default=DEFAULT_PHASE_NAME)
    parser.add_argument("--fork-run-id", default=None, help="optional run_id for the release branch")
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    try:
        manifest = RunManifest.model_validate_json(Path(args.manifest).read_text(encoding="utf-8"))
        cfg = load_run_config(args.config, *args.overlay)
        result = fork_release(
            args.checkpoint,
            args.out,
            manifest=manifest,
            cfg=cfg,
            anneal_dataset=args.anneal_dataset,
            decay_tokens=args.decay_tokens,
            effective_window=args.effective_window,
            committed_block=args.committed_block,
            phase_name=args.phase_name,
            fork_run_id=args.fork_run_id,
        )
    except (ForkError, FileExistsError, FileNotFoundError, ValueError) as exc:
        print(f"release fork failed: {exc}", file=sys.stderr)
        return 2
    print(f"forked manifest : {result.manifest_path}")
    print(f"manifest_hash   : {result.manifest.manifest_hash()}")
    print(f"decay start step: {result.decay_start_step} (peak_lr {result.peak_lr})")
    print(f"runbook         : {result.runbook_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
